"""PDF export of a single student's graded result for EduGrade AI.

Builds a printable A4 report card from the result dict returned by
``GemmaHelper.evaluate_paper``: student details, score summary with a letter
grade, a per-question marks table, per-question and overall feedback, a
teacher sign-off line and (optionally) the scanned answer sheet as an appendix.

Uses fpdf2's built-in Helvetica font, which only covers Latin-1, so all text
is passed through :func:`_safe` to replace characters it cannot draw (curly
quotes, dashes, emoji, ...) instead of crashing.
"""

from __future__ import annotations

from datetime import date
from typing import Any, Dict, List, Optional, Tuple

from fpdf import FPDF
from fpdf.enums import XPos, YPos
from fpdf.fonts import FontFace
from PIL import Image

# Common West African secondary-school scale (WAEC-style), highest first.
GRADE_SCALE: List[Tuple[float, str, str]] = [
    (70, "A", "Excellent"),
    (60, "B", "Very good"),
    (50, "C", "Credit"),
    (45, "D", "Pass"),
    (40, "E", "Fair"),
    (0, "F", "Needs improvement"),
]

ACCENT = (37, 99, 235)
TEXT = (15, 23, 42)
MUTED = (100, 116, 139)
LIGHT_FILL = (241, 245, 249)
SUCCESS = (16, 122, 87)
DANGER = (185, 28, 28)
WARNING = (180, 83, 9)

_REPLACEMENTS = {
    "‘": "'", "’": "'", "“": '"', "”": '"',
    "–": "-", "—": "-", "…": "...", "•": "-",
    " ": " ", "→": "->", "←": "<-", "≤": "<=",
    "≥": ">=", "≠": "!=", "×": "x", "√": "sqrt",
}


def _safe(value: Any) -> str:
    """Return ``value`` as text that the core Latin-1 PDF fonts can render."""
    text = "" if value is None else str(value)
    for bad, good in _REPLACEMENTS.items():
        text = text.replace(bad, good)
    return text.encode("latin-1", errors="ignore").decode("latin-1")


def _num(value: Any) -> str:
    """Format a mark without a trailing ``.0`` (2.0 -> "2", 1.5 -> "1.5")."""
    try:
        f = float(value)
    except (TypeError, ValueError):
        return _safe(value)
    return str(int(f)) if f.is_integer() else f"{f:g}"


def letter_grade(percentage: float) -> Tuple[str, str]:
    """Map a percentage to ``(letter, remark)`` using :data:`GRADE_SCALE`."""
    for threshold, letter, remark in GRADE_SCALE:
        if percentage >= threshold:
            return letter, remark
    return GRADE_SCALE[-1][1], GRADE_SCALE[-1][2]


def _status(q: Dict[str, Any], exam_type: str) -> Tuple[str, Tuple[int, int, int]]:
    if exam_type == "objective":
        return ("Correct", SUCCESS) if q.get("is_correct") else ("Incorrect", DANGER)
    closeness = str(q.get("closeness") or "").lower()
    mapping = {
        "exact": ("Exact", SUCCESS),
        "close": ("Close", SUCCESS),
        "partial": ("Partial", WARNING),
        "incorrect": ("Incorrect", DANGER),
        "off-topic": ("Off-topic", DANGER),
    }
    return mapping.get(closeness, (closeness.title() or "-", MUTED))


class _ReportPDF(FPDF):
    def footer(self) -> None:  # noqa: D401 - fpdf hook
        self.set_y(-12)
        self.set_font("helvetica", "", 8)
        self.set_text_color(*MUTED)
        self.cell(0, 6, "Generated by EduGrade AI - AI-assisted grading; please review before sharing.", align="L")
        self.cell(0, 6, f"Page {self.page_no()}/{{nb}}", align="R")


def generate_student_report_pdf(
    result: Dict[str, Any],
    *,
    student_name: str = "",
    student_id: str = "",
    class_name: str = "",
    subject: str = "",
    topic: str = "",
    max_score: Optional[float] = None,
    answer_sheet: Optional[Image.Image] = None,
    report_date: Optional[date] = None,
) -> bytes:
    """Render one student's graded result as a PDF and return its bytes."""
    exam_type = str(result.get("exam_type") or "theory").lower()
    total = float(result.get("total_score") or 0)
    maximum = float(result.get("max_score") or max_score or 0)
    pct = (total / maximum * 100) if maximum else 0.0
    letter, remark = letter_grade(pct)

    pdf = _ReportPDF(format="A4")
    pdf.set_title(_safe(f"EduGrade AI result - {student_name or 'Student'}"))
    pdf.set_author("EduGrade AI")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(15, 15, 15)
    pdf.add_page()
    width = pdf.epw

    # ---- Header band -------------------------------------------------
    pdf.set_fill_color(*ACCENT)
    pdf.rect(0, 0, pdf.w, 28, style="F")
    pdf.set_xy(15, 8)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("helvetica", "B", 18)
    pdf.cell(width * 0.6, 8, "Student Result Report")
    pdf.set_font("helvetica", "", 10)
    pdf.cell(width * 0.4, 8, _safe((report_date or date.today()).strftime("%d %B %Y")), align="R",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_x(15)
    pdf.cell(0, 6, "EduGrade AI - paper-to-digital grade assistant")
    pdf.set_y(36)

    # ---- Student / assessment details -------------------------------
    details = [
        ("Student name", student_name or "-"),
        ("Student ID / Adm. no.", student_id or "-"),
        ("Class", class_name or "-"),
        ("Subject", subject or "-"),
        ("Topic", topic or result.get("topic") or "-"),
        ("Exam type", "Objective" if exam_type == "objective" else "Theory"),
    ]
    pdf.set_text_color(*TEXT)
    label_w, value_w = 38, width / 2 - 38
    for i in range(0, len(details), 2):
        for label, value in details[i:i + 2]:
            pdf.set_font("helvetica", "B", 10)
            pdf.set_text_color(*MUTED)
            pdf.cell(label_w, 7, _safe(label))
            pdf.set_font("helvetica", "", 10)
            pdf.set_text_color(*TEXT)
            pdf.cell(value_w, 7, _safe(value)[:48])
        pdf.ln(7)
    pdf.ln(4)

    # ---- Score summary boxes ----------------------------------------
    box_w, box_h, gap = (width - 2 * 6) / 3, 22, 6
    y = pdf.get_y()
    boxes = [
        ("Score", f"{_num(total)} / {_num(maximum)}"),
        ("Percentage", f"{pct:.0f}%"),
        ("Grade", f"{letter} - {remark}"),
    ]
    for i, (label, value) in enumerate(boxes):
        x = 15 + i * (box_w + gap)
        pdf.set_fill_color(*LIGHT_FILL)
        pdf.set_draw_color(203, 213, 225)
        pdf.rect(x, y, box_w, box_h, style="DF", round_corners=True, corner_radius=2)
        pdf.set_xy(x, y + 3)
        pdf.set_font("helvetica", "", 9)
        pdf.set_text_color(*MUTED)
        pdf.cell(box_w, 5, label.upper(), align="C")
        pdf.set_xy(x, y + 9)
        pdf.set_font("helvetica", "B", 15 if i < 2 else 12)
        pdf.set_text_color(*ACCENT)
        pdf.cell(box_w, 9, _safe(value), align="C")
    pdf.set_y(y + box_h + 8)

    # ---- Per-question table -----------------------------------------
    def section(title: str) -> None:
        pdf.set_font("helvetica", "B", 13)
        pdf.set_text_color(*TEXT)
        pdf.cell(0, 8, title, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_draw_color(*ACCENT)
        pdf.set_line_width(0.6)
        pdf.line(15, pdf.get_y(), 15 + 20, pdf.get_y())
        pdf.set_line_width(0.2)
        pdf.ln(3)

    section("Per-question breakdown")
    breakdown = result.get("question_breakdown") or []
    if breakdown:
        expected_header = "Correct answer" if exam_type == "objective" else "Expected answer"
        pdf.set_font("helvetica", "", 9)
        pdf.set_draw_color(203, 213, 225)
        heading = FontFace(emphasis="BOLD", color=(255, 255, 255), fill_color=ACCENT)
        with pdf.table(
            col_widths=(10, 62, 62, 24, 22),
            text_align=("CENTER", "LEFT", "LEFT", "CENTER", "CENTER"),
            headings_style=heading,
            line_height=5.5,
            padding=1.5,
            cell_fill_color=(248, 250, 252),
            cell_fill_mode="ROWS",
        ) as table:
            header = table.row()
            for h in ("Q", "Student answer", expected_header, "Result", "Marks"):
                header.cell(h)
            for q in breakdown:
                status, colour = _status(q, exam_type)
                expected = q.get("correct_answer") or q.get("reference_answer") or "-"
                row = table.row()
                row.cell(_num(q.get("question_number", "?")))
                row.cell(_safe(q.get("student_answer") or "-"))
                row.cell(_safe(expected))
                row.cell(status, style=FontFace(emphasis="BOLD", color=colour))
                row.cell(f"{_num(q.get('marks_awarded', 0))} / {_num(q.get('max_marks', 0))}")
        pdf.ln(5)

        feedback_rows = [q for q in breakdown if q.get("feedback")]
        if feedback_rows:
            section("Feedback by question")
            for q in feedback_rows:
                pdf.set_font("helvetica", "B", 10)
                pdf.set_text_color(*TEXT)
                pdf.cell(12, 6, f"Q{_num(q.get('question_number', '?'))}")
                pdf.set_font("helvetica", "", 10)
                pdf.multi_cell(0, 6, _safe(q["feedback"]), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
                pdf.ln(1)
            pdf.ln(3)
    else:
        pdf.set_font("helvetica", "I", 10)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 7, "No per-question breakdown was returned for this paper.",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(4)

    # ---- Overall feedback --------------------------------------------
    section("Teacher's comments")
    pdf.set_font("helvetica", "", 10.5)
    pdf.set_text_color(*TEXT)
    pdf.set_fill_color(*LIGHT_FILL)
    pdf.multi_cell(0, 6.5, _safe(result.get("overall_feedback") or "-"), fill=True, padding=3,
                   new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(14)

    # ---- Sign-off ------------------------------------------------------
    if pdf.get_y() > pdf.h - 40:
        pdf.add_page()
    pdf.set_draw_color(*MUTED)
    y = pdf.get_y()
    pdf.line(15, y, 85, y)
    pdf.line(width - 55, y, width + 15, y)
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(*MUTED)
    pdf.cell(width - 70, 5, "Teacher's signature")
    pdf.cell(70, 5, "Parent / guardian's signature", align="R")

    # ---- Appendix: scanned answer sheet ------------------------------
    if answer_sheet is not None:
        pdf.add_page()
        section("Appendix - student's answer sheet")
        img = answer_sheet.convert("RGB")
        img.thumbnail((1600, 1600))  # keep the PDF small
        max_w, max_h = width, pdf.h - pdf.get_y() - 20
        scale = min(max_w / img.width, max_h / img.height)
        w, h = img.width * scale, img.height * scale
        x, y = 15 + (width - w) / 2, pdf.get_y()
        pdf.image(img, x=x, y=y, w=w, h=h)
        pdf.set_draw_color(203, 213, 225)
        pdf.rect(x, y, w, h)

    return bytes(pdf.output())


def report_filename(student_name: str) -> str:
    """Build a filesystem-safe PDF name such as ``ada_obi_result.pdf``."""
    slug = "".join(c.lower() if c.isalnum() else "_" for c in student_name.strip())
    slug = "_".join(part for part in slug.split("_") if part)
    return f"{slug or 'student'}_result.pdf"
